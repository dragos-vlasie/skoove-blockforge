import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const projectRoot = new URL("../", import.meta.url).pathname;
const output = join(projectRoot, "src/blocks/nextRegistry.tsx");
const roots = [join(projectRoot, "src/blocks"), join(projectRoot, "src/packs")];

const walk = (directory) => readdirSync(directory).flatMap((name) => {
  const path = join(directory, name);
  return statSync(path).isDirectory() ? walk(path) : [path];
});

const viewFiles = roots.flatMap(walk).filter((path) => path.endsWith("/View.tsx"));
const records = viewFiles.map((viewPath) => {
  const definitionPath = join(dirname(viewPath), "definition.ts");
  const previewPath = join(dirname(viewPath), "Preview.tsx");
  const viewSource = readFileSync(viewPath, "utf8");
  const definitionSource = readFileSync(definitionPath, "utf8");
  const viewName = viewSource.match(/export function\s+([A-Za-z0-9_]+)/)?.[1];
  const typeName = definitionSource.match(/type:\s*BlockType\.([A-Z0-9_]+)/)?.[1];
  if (!viewName || !typeName) throw new Error(`Unable to inspect ${viewPath}`);
  const modulePath = `./${relative(dirname(output), viewPath).replace(/\\/g, "/").replace(/\.tsx$/, "")}`;
  const definitionModulePath = `./${relative(dirname(output), definitionPath).replace(/\\/g, "/").replace(/\.ts$/, "")}`;
  const previewModulePath = `./${relative(dirname(output), previewPath).replace(/\\/g, "/").replace(/\.tsx$/, "")}`;
  return { definitionModulePath, modulePath, previewModulePath, typeName, viewName };
}).sort((a, b) => a.typeName.localeCompare(b.typeName));

const source = `/* Generated by scripts/generate-next-block-registry.mjs. */
import type { ComponentType } from "react";
import { BlockType } from "../../types";
${records.map((record, index) => `import definition${index} from "${record.definitionModulePath}";\nimport { ${record.viewName} } from "${record.modulePath}";\nimport { Preview as Preview${index} } from "${record.previewModulePath}";`).join("\n")}

export const nextBlockEntries = [
${records.map((record, index) => `  { definition: definition${index}, folder: "${record.modulePath.split("/").at(-2)}", moduleRoot: "${record.modulePath.replace(/\/View$/, "")}" },`).join("\n")}
] as const;

export const nextBlockViews = {
${records.map((record) => `  [BlockType.${record.typeName}]: ${record.viewName},`).join("\n")}
} as unknown as Record<BlockType, ComponentType<any>>;

export const nextBlockPreviews = {
${records.map((record, index) => `  [BlockType.${record.typeName}]: Preview${index},`).join("\n")}
} as unknown as Record<BlockType, ComponentType<any>>;
`;

writeFileSync(output, source);
console.log(`Generated ${output} with ${records.length} blocks.`);
