import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const manifestPath = join(projectRoot, "blockforge.extension.json");
const outputPath = join(projectRoot, "src/extensions/generatedViews.ts");

let blocks = [];
if (existsSync(manifestPath)) {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.blocks)) {
    throw new Error("blockforge.extension.json must use schemaVersion 1 and contain a blocks array.");
  }

  const blockTypes = new Set();
  blocks = manifest.blocks.map((block) => {
    if (!/^CUSTOM:[A-Z0-9][A-Z0-9_-]*$/.test(block.type)) {
      throw new Error(`Invalid client extension block type: ${block.type}`);
    }
    if (!/^src\/[a-zA-Z0-9_./-]+$/.test(block.viewModule) || block.viewModule.includes("..")) {
      throw new Error(`Invalid viewModule for ${block.type}. Use a path inside src/.`);
    }
    if (blockTypes.has(block.type)) {
      throw new Error(`Duplicate client extension block type: ${block.type}`);
    }
    blockTypes.add(block.type);

    const absoluteModule = resolve(projectRoot, block.viewModule);
    if (!absoluteModule.startsWith(resolve(projectRoot, "src") + "/")) {
      throw new Error(`Client extension view for ${block.type} must stay inside src/.`);
    }
    const importPath = `./${relative(dirname(outputPath), absoluteModule).replace(/\\/g, "/")}`;
    return { type: block.type, importPath };
  });
}

const source = `/* Generated by scripts/generate-client-extension-registry.mjs. */
import type { ComponentType } from "react";
${blocks.map((block, index) => `import ExtensionView${index} from "${block.importPath}";`).join("\n")}

export const generatedClientExtensionViews = {
${blocks.map((block, index) => `  "${block.type}": ExtensionView${index},`).join("\n")}
} as Record<string, ComponentType<any>>;
`;

writeFileSync(outputPath, source);
console.log(`Generated ${outputPath} with ${blocks.length} client extension views.`);
